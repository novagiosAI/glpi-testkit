"""Integration tests against a live GLPI server.

Skipped unless ``GLPI_TEST_URL`` is set, so the default run stays offline.

These prove the two claims the package rests on: that generated tickets are
accepted by the real API unchanged, and that the priority matrix reproduced in
:mod:`glpi_testkit.priority` is the one GLPI actually applies.

    export GLPI_TEST_URL=http://localhost:8011/apirest.php
    export GLPI_TEST_APP_TOKEN=...
    export GLPI_TEST_USER_TOKEN=...
    pytest tests/test_integration_glpi.py -v
"""

from __future__ import annotations

import os

import pytest

from glpi_testkit import Language, TicketGenerator, compute_priority

URL = os.environ.get("GLPI_TEST_URL")
APP_TOKEN = os.environ.get("GLPI_TEST_APP_TOKEN", "")
USER_TOKEN = os.environ.get("GLPI_TEST_USER_TOKEN", "")

pytestmark = pytest.mark.skipif(
    not URL, reason="set GLPI_TEST_URL to run integration tests"
)

glpi_rest = pytest.importorskip("glpi_rest", reason="install the 'glpi' extra")


@pytest.fixture(scope="module")
def client():
    with glpi_rest.GLPIClient(URL, app_token=APP_TOKEN, user_token=USER_TOKEN) as glpi:
        yield glpi


@pytest.fixture(scope="module")
def pushed(client):
    """Create a batch of generated tickets, and purge them afterwards."""
    tickets = TicketGenerator(seed=2026).generate(20)
    created = []
    for ticket in tickets:
        result = client.add_item("Ticket", ticket.to_glpi_input())
        created.append((result["id"], ticket))
    try:
        yield created
    finally:
        for ticket_id, _ in created:
            client.delete_item("Ticket", ticket_id, force_purge=True)


def test_every_generated_ticket_is_accepted(pushed):
    """to_glpi_input() must produce something the API takes as-is."""
    assert len(pushed) == 20
    assert all(isinstance(ticket_id, int) for ticket_id, _ in pushed)


def test_text_survives_the_round_trip(client, pushed):
    """Arabic and Darija must come back byte-for-byte."""
    for ticket_id, original in pushed:
        stored = client.get_item("Ticket", ticket_id)
        assert stored["name"] == original.name


def test_glpi_computes_the_same_priority(client, pushed):
    """The real check on our priority matrix: GLPI recomputes priority from
    urgency and impact, so a mismatch means our table is wrong."""
    for ticket_id, original in pushed:
        stored = client.get_item("Ticket", ticket_id)
        assert int(stored["urgency"]) == int(original.urgency)
        assert int(stored["impact"]) == int(original.impact)
        assert int(stored["priority"]) == int(original.priority), (
            f"ticket {ticket_id}: GLPI says {stored['priority']}, "
            f"we predicted {int(original.priority)}"
        )


def test_priority_matrix_matches_the_server_for_every_pair(client):
    """Exhaustive check of all 25 urgency/impact combinations."""
    created: list[int] = []
    try:
        for urgency in range(1, 6):
            for impact in range(1, 6):
                result = client.add_item(
                    "Ticket",
                    {
                        "name": f"matrix probe u{urgency} i{impact}",
                        "content": "generated by glpi-testkit test suite",
                        "urgency": urgency,
                        "impact": impact,
                    },
                )
                created.append(result["id"])
                stored = client.get_item("Ticket", result["id"])
                assert int(stored["priority"]) == int(
                    compute_priority(urgency, impact)
                ), f"u={urgency} i={impact}: GLPI says {stored['priority']}"
    finally:
        for ticket_id in created:
            client.delete_item("Ticket", ticket_id, force_purge=True)


@pytest.mark.parametrize("language", list(Language))
def test_each_language_is_accepted(client, language):
    ticket = TicketGenerator(seed=7, languages=[language]).generate(1)[0]
    result = client.add_item("Ticket", ticket.to_glpi_input())
    try:
        stored = client.get_item("Ticket", result["id"])
        assert stored["name"] == ticket.name
        assert stored["content"]
    finally:
        client.delete_item("Ticket", result["id"], force_purge=True)
